def state_wait(self,step):
    op=step["op"];p=self.page;b=self.backend
    latest=None
    def observed():
        nonlocal latest
        latest=b.core.store.get('task',step['task_id'])
        return latest if latest and latest['status']==step['status'] else None
    try:return until(observed,step.get('timeout',30))
    except TimeoutError as error:
        facts={key:(latest or {}).get(key) for key in ('id','status','standby','no_input_reports','start_at','end_at')}
        raise TimeoutError('Expected task status '+step['status']+'; last observed '+json.dumps(facts)) from error

def shell_run(self,step):
    op=step["op"];p=self.page;b=self.backend
    argv = step.get('argv')
    if argv is None:
        if step.get('shell') == 'powershell' or (step.get('shell') is None and sys.platform == 'win32'):
            argv = ['powershell', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', '[Console]::OutputEncoding=[System.Text.UTF8Encoding]::new(); ' + step['command']]
        else:
            argv = ['bash', '-lc', step['command']] if step.get('sudo') is None else ['sudo', 'bash', '-lc', step['command']] if step.get('sudo') else ['bash', '-lc', step['command']]
    result = subprocess.run(argv, capture_output=True, cwd=str(ROOT), timeout=step.get('timeout', 120), creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
    output = (result.stdout + result.stderr).decode('utf-8', 'replace')
    if result.returncode and (not step.get('allow_failure')):
        raise RuntimeError('shell 失败(' + str(result.returncode) + ')：' + output[-500:])
    return {'code': result.returncode, 'output': output}

def state_read(self,step):
    op=step["op"];p=self.page;b=self.backend
    state=b.core.state()
    if step.get('task_id'):
        task_id=step['task_id']
        state={**state,**{key:[row for row in state.get(key,[]) if row.get('id' if key in ('tasks','live') else 'task_id')==task_id] for key in ('tasks','live','reports','alerts')}}
    return state

def state_fields(self,step):
    op=step["op"];p=self.page;b=self.backend
    return until(lambda: task if (task := b.core.store.get('task', step['task_id'])) and all((task.get(k) == v for k, v in step['expected'].items())) else None, step.get('timeout', 30))

def backend_restart(self,step):
    op=step["op"];p=self.page;b=self.backend
    b.restart()
    return b.core.state()

def report_drain(self,step):
    # Establish an observation boundary after a fixture/UI change. Product
    # delivery continues normally; do not release or rewrite report state.
    reports=self.backend.core.store.all('report')
    self.observed_reports.update(r['id'] for r in reports)
    return {'observed_before_next_phase':[r['id'] for r in reports]}

def report_preview(self,step):
    # Legacy spelling: observe the next report generated by the real service.
    seen=getattr(self,'observed_reports',set())
    def observed():
        return next((r for r in self.backend.core.store.all('report') if r['id'] not in seen),None)
    report=until(observed,step.get('timeout',60))
    seen.add(report['id']);self.observed_reports=seen
    return report

def report_release(self,step):
    # No release endpoint: the real DSH heartbeat owns delivery and review.
    return until(lambda:r if (r:=self.backend.core.store.get('report',step['report_id'])) and r['status']=='reviewed' else None,step.get('timeout',60))

