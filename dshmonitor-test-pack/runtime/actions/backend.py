def report_wait(self,step):
    latest=[]
    def observed():
        nonlocal latest
        reports=self.backend.core.store.all('report')
        latest=[r for r in reports if r['task_id']==step['task_id']][-5:]
        return next((r for r in reversed(reports) if r['task_id']==step['task_id']
                     and r.get('status')==step.get('status','reviewed')
                     and r['id'] not in step.get('exclude',[])
                     and r.get('created_at',0)>step.get('created_after',0)
                     and (not step.get('phase') or r.get('phase')==step['phase'])
                     and (not step.get('sampled_after') or (r.get('raw',{}).get('real_end') or 0)>step['sampled_after'])
                     and (not step.get('sampled_from_after') or (r.get('raw',{}).get('real_start') or 0)>step['sampled_from_after'])
                     and len(r.get('raw',{}).get('source_sample_ids',[]))>=step.get('minimum_samples',0)
                     and r.get('raw',{}).get('unobserved_gap_seconds',0)>=step.get('minimum_gap_seconds',0)
                     and (not step.get('metadata_after') or any(e.get('id')==step['window_id'] and (e.get('metadata_captured_at') or 0)>step['metadata_after'] for e in r.get('raw',{}).get('evidence',{}).values()))
                     and (not step.get('text_contains') or any(e.get('id')==step['window_id'] and step['text_contains'] in (e.get('ui_text') or '') for e in r.get('raw',{}).get('evidence',{}).values()))
                     and (not step.get('screenshot_scope') or any(e.get('id')==step['window_id'] and (e.get('screenshot') or {}).get('scope')==step['screenshot_scope'] for e in r.get('raw',{}).get('evidence',{}).values()))
                     and (not step.get('detail_after') or any(e.get('id')==step['window_id'] and (e.get('details_captured_at') or 0)>step['detail_after'] for e in r.get('raw',{}).get('evidence',{}).values()))),None)
    try:return until(observed,step.get('timeout',60),wait=lambda seconds:self.page.wait_for_timeout(seconds*1000))
    except TimeoutError:
        evidence=[]
        for r in latest:
            raw=r.get('raw',{})
            evidence.append({'id':r['id'],'status':r.get('status'),'phase':r.get('phase'),
                'created_at':r.get('created_at'),'real_end':raw.get('real_end'),
                'samples':len(raw.get('source_sample_ids',[])),
                'windows':[{**{k:e.get(k) for k in ('id','title','visible','focused','metadata_captured_at','details_captured_at','ui_text_error','screenshot_error')},'screenshot_scope':(e.get('screenshot') or {}).get('scope')}
                           for e in raw.get('evidence',{}).values() if not step.get('window_id') or e.get('id')==step['window_id']]})
        diagnostic={'expected':step,'reports':evidence,'state':self.backend.state()}
        diagnostic['state_observation']=getattr(self.backend,'state_observation',None)
        if os.name=='nt':
            import psutil
            processes=[]
            for process in psutil.process_iter(['pid','ppid','cmdline','create_time','status']):
                if any('windows_service.py' in arg for arg in process.info.get('cmdline') or []):
                    processes.append({k:v for k,v in process.info.items() if k!='cmdline'})
            diagnostic['service_processes']=processes
        (self.out/(step.get('id','report-wait')+'-timeout.json')).write_text(json.dumps(diagnostic,ensure_ascii=False,indent=2),encoding='utf-8')
        raise

def report_target(self,step):
    report=self.backend.core.store.get('report',step['report_id'])
    entity=self.entities.items[step['entity']]
    candidates=report['effective']['evidence']
    # Stable native ID/PID from the fixture, never a title guess.
    kind=step.get('kind','window')
    matches=[{'ref':ref,'evidence':e} for ref,e in candidates.items()
             if e.get('kind')==kind and e.get('pid')==entity['pid']
             and ((kind=='browser_tab' and ((e.get('tab_id') is not None and str(e['tab_id'])==str(entity.get('tab_id')))
                                           or (e.get('tab_id') is None and entity.get('tab_id') is None and e.get('native_window_id')==entity['window_id'])))
                  or (kind=='window' and (e.get('id')==entity['window_id'] or str(e.get('native_id'))==entity['window_id'].split(':')[-1])))]
    if not matches:raise AssertionError('Formal report lacks '+kind+' target for '+step['entity'])
    # Evidence keys may be sorted during serialization; their order is not time.
    return max(matches,key=lambda row:row['evidence'].get('source_sample_id',0))

def connection_probe(self,step):
    # Explicit failure injection: an unused endpoint, never a replacement service.
    import urllib.request
    with urllib.request.urlopen(step['url'],timeout=step.get('timeout',3)) as response:
        return {'status':response.status}

def session_save(self,step):
    directory=Path(os.environ['DSH_TEST_SESSION_DIRECTORY'])
    saved={key:self.values[key] for key in step['keys']}
    (directory/'checkpoint.json').write_text(json.dumps(saved,ensure_ascii=False),encoding='utf-8')
    # The next phase owns cleanup of this exact task; no pre-existing task is touched.
    self.backend.original_tasks.add(saved['task']['value']['id'])
    self.backend.defer_settings_restore=True
    return saved

def session_load(self,step):
    saved=json.loads((Path(os.environ['DSH_TEST_SESSION_DIRECTORY'])/'checkpoint.json').read_text(encoding='utf-8'))
    self.values.update(saved)
    return saved

def service_observe(self,step):
    """Read service reachability and processes without waking or keeping it alive."""
    import psutil
    started=time.monotonic();samples=[]
    while True:
        row={'elapsed':round(time.monotonic()-started,3),'at':time.time()}
        try:
            state=self.backend.request('/state',{})
            row.update(reachable=True,live_tasks=[t['id'] for t in state.get('live',[])],capture_state=state.get('capture_state'),capture_error=state.get('capture_error'),last_sample_at=state.get('last_sample_at'))
        except (OSError,RuntimeError,http.client.HTTPException) as error:
            row.update(reachable=False,error=f'{type(error).__name__}: {error}')
        row['status_files']={}
        for name in ('status.json','settings.json'):
            try:
                stat=(self.backend.directory/name).stat()
                row['status_files'][name]=[stat.st_mtime_ns,stat.st_ctime_ns,stat.st_size]
            except FileNotFoundError:row['status_files'][name]=None
        processes=[]
        for process in psutil.process_iter(['pid','create_time','cmdline']):
            command=process.info['cmdline'] or []
            if any(Path(arg).name in ('chat_service.py','windows_service.py','chat_sensor.py') for arg in command):
                processes.append({'pid':process.pid,'created_at':process.info['create_time']})
        row['processes']=processes
        if sys.platform!='win32':
            from focus_demo.desktop_bridge import call
            try:row['bridge']=call('status')
            except Exception as error:row['bridge']={'error':str(error)}
        samples.append(row)
        remaining=step.get('seconds',0)-(time.monotonic()-started)
        if remaining<=0:break
        time.sleep(min(step.get('interval',.25),remaining))
    captures=[r.get('last_sample_at') for r in samples if r.get('reachable')]
    bridge_delta=({key:samples[-1]['bridge'][key]-samples[0]['bridge'][key] for key in ('snapshots','screenshots')} if all(key in row.get('bridge',{}) for row in (samples[0],samples[-1]) for key in ('snapshots','screenshots')) else None) if sys.platform!='win32' else {}
    return {'samples':samples,'last':samples[-1],'status_file_changes':sum(a['status_files']!=b['status_files'] for a,b in zip(samples,samples[1:])),'sample_changes':sum(a!=b for a,b in zip(captures,captures[1:])),'bridge_delta':bridge_delta,'capture_changes':max([sum(a!=b for a,b in zip(captures,captures[1:])),*(bridge_delta or {}).values()])}

def sample_inspect(self,step):
    samples=self.backend.core.store.read('samples',step['task_id'])
    samples=[r for r in samples if r['ts']>step.get('after',0)]
    intervals=[b['mono']-a['mono'] for a,b in zip(samples,samples[1:])]
    identity=self.entities.items.get(step.get('entity'),{})
    windows=[w for r in samples for w in r['desktop'].get('windows',[]) if w['id']==identity.get('window_id')]
    shots=[w['screenshot'] for w in windows if w.get('screenshot')]
    texts=[w.get('ui_text','') for w in windows if w.get('ui_text')]
    logs=[log for w in windows for log in w.get('logs',[]) if log.get('source')=='open_regular_log_file']
    semantics=[r.get('browser',{}).get('semantic',{}) for r in samples]
    metrics={'image_count':len(shots),'max_width':max((p['width'] for p in shots),default=0),'max_height':max((p['height'] for p in shots),default=0),
             'text_count':len(texts),'max_text_chars':max(map(len,texts),default=0),'max_nodes':max(((w.get('ui_structure')or{}).get('captured_nodes',0) for w in windows),default=0),
             'log_count':len(logs),'max_log_chars':max((len(v.get('text','')) for v in logs),default=0),'log_text':'\n'.join(v.get('text','') for v in logs),
             'image_times':sorted({p['captured_at'] for p in shots}),'text_times':sorted({w['text_captured_at'] for w in windows if w.get('text_captured_at')}),
             'max_image_age':max((r['ts']-w['screenshot']['captured_at'] for r in samples for w in r['desktop'].get('windows',[]) if w['id']==identity.get('window_id') and w.get('screenshot')),default=0),
             'log_times':sorted({w['logs_captured_at'] for w in windows if w.get('logs_captured_at')}),
             'browser_capture_counts':[len(v.get('snapshots',[])) for v in semantics],
             'browser_max_pages':max((len(v.get('snapshots',[])) for v in semantics),default=0),
             'browser_max_chars':max((len(p.get('snapshot',{}).get('text','')) for v in semantics for p in v.get('snapshots',[])),default=0),
             'browser_titles':sorted({p.get('title','') for v in semantics for p in v.get('snapshots',[]) if p.get('snapshot')})}
    return {'metrics':metrics,'count':len(samples),'intervals':intervals,'max_interval':max(intervals,default=0),
            'frames':[{'ts':r['ts'],'settings':r.get('settings'),'available':r['desktop'].get('available'),
                       'screen':r['desktop'].get('desktop_screenshot'),
                       'windows':[{k:w.get(k) for k in ('id','title','focused','visible','ui_text','ui_structure','text_scope','detail_notes','screenshot','logs','text_captured_at','logs_captured_at')} for w in r['desktop'].get('windows',[])],
                       'browser':r.get('browser',{}).get('semantic')} for r in samples],
            'browser_observations':[{'sample_id':r['sample_id'],'ts':r['ts'],**{key:r.get('browser',{}).get('semantic',{}).get(key) for key in ('captured_at','cache_age_seconds','limitations')}} for r in samples],
            'capture_timings':[{'sample_id':r['sample_id'],**r.get('capture_timings',{})} for r in samples]}

